/**
 * Refreshes src/data/snapshot.ts from the live Sessionize feeds.
 * The snapshot is the fallback used when Sessionize can't be reached.
 *
 *   npm run update-snapshot
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { fetchFeeds } from "../src/data/agenda.js";
import type { RawFeeds } from "../src/data/types.js";

const feeds = await fetchFeeds();

// Keep only the fields the server uses, to keep the bundle small.
const trimmed: RawFeeds = {
  grid: feeds.grid.map((d) => ({
    date: d.date,
    rooms: d.rooms.map((r) => ({
      id: r.id,
      name: r.name,
      sessions: r.sessions.map((s) => ({
        id: s.id,
        title: s.title,
        description: s.description,
        startsAt: s.startsAt,
        endsAt: s.endsAt,
        isServiceSession: s.isServiceSession,
        isPlenumSession: s.isPlenumSession,
        speakers: s.speakers.map((p) => ({ id: p.id, name: p.name })),
        categories: s.categories.map((c) => ({
          id: c.id,
          name: c.name,
          categoryItems: c.categoryItems.map((i) => ({ id: i.id, name: i.name })),
        })),
        roomId: s.roomId,
        room: s.room,
      })),
    })),
  })),
  speakers: feeds.speakers.map((p) => ({
    id: p.id,
    fullName: p.fullName,
    bio: p.bio,
    tagLine: p.tagLine,
    profilePicture: p.profilePicture,
    links: (p.links ?? []).map((l) => ({ title: l.title, url: l.url, linkType: l.linkType })),
    sessions: (p.sessions ?? []).map((s) => ({ id: s.id, name: s.name })),
  })),
};

const out = fileURLToPath(new URL("../src/data/snapshot.ts", import.meta.url));
const body =
  "// Generated by `npm run update-snapshot` — do not edit by hand.\n" +
  'import type { RawFeeds } from "./types.js";\n\n' +
  `export const SNAPSHOT: { fetchedAt: string; feeds: RawFeeds } = ${JSON.stringify(
    { fetchedAt: new Date().toISOString(), feeds: trimmed },
    null,
    1,
  )};\n`;
writeFileSync(out, body);

const count = trimmed.grid.reduce(
  (n, d) => n + d.rooms.reduce((m, r) => m + r.sessions.length, 0),
  0,
);
console.log(`Wrote ${out}: ${count} agenda entries, ${trimmed.speakers.length} speakers.`);
